BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.FACTURA_DETALLE', N'U') IS NULL
    CREATE TABLE dbo.FACTURA_DETALLE (
        ID_FACTURA int NOT NULL REFERENCES dbo.FACTURA(ID_FACTURA),
        ID_CELULAR int NOT NULL REFERENCES dbo.CELULAR(ID_CELULAR),
        NOMBRE_CELULAR nvarchar(100) NOT NULL,
        PRECIO numeric(10,2) NOT NULL CHECK (PRECIO > 0),
        CONSTRAINT PK_FACTURA_DETALLE PRIMARY KEY (ID_FACTURA, ID_CELULAR)
    );

INSERT dbo.FACTURA_DETALLE (ID_FACTURA, ID_CELULAR, NOMBRE_CELULAR, PRECIO)
SELECT f.ID_FACTURA, f.ID_CELULAR, f.NOMBRE_CELULAR, f.PRECIO
FROM dbo.FACTURA f WITH (UPDLOCK, HOLDLOCK)
WHERE NOT EXISTS (SELECT 1 FROM dbo.FACTURA_DETALLE d WHERE d.ID_FACTURA = f.ID_FACTURA);

COMMIT TRANSACTION;
GO
